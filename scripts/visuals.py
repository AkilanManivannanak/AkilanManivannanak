def render_all(groups, labels, latest, stats, days, blurb_fn, classify_fn):
    """Writes every card in both themes. Returns the names written, for the README."""
    total = sum(len(v) for v in groups.values())
    for mode in PAL:
        for f in FLAGSHIPS:
            _write(f"card-{f['repo']}", mode, project_card(f, mode))
        for d, rs in groups.items():
            if rs:
                _write(f"domain-{d}", mode, domain_tile(d, labels[d], rs, total, mode))
        for i, r in enumerate(latest):
            d = classify_fn(r)
            _write(f"latest-{i + 1}", mode, latest_card(r, labels[d], d, blurb_fn(r), mode, i))
        _write("pulse", mode, pulse(stats, days or [], mode))
        _write("ledger", mode, ledger_card(mode))
