def pulse(stats, days, mode):
    """stats: list of (label, value_str, fraction 0..1). days: [{'d','c'}] newest last."""
    p = PAL[mode]
    W, H = 1200, 250
    blocks = []
    for i, (label, value, frac) in enumerate(stats[:4]):
        x = 32 + i * 150
        col = [p["amber"], p["teal"], p["sky"], p["violet"]][i]
        blocks.append(f'''
<g opacity="0"><animate attributeName="opacity" values="0;1" begin="{i * .2:.1f}s" dur=".5s" fill="freeze"/>
  <text x="{x}" y="112" fill="{p["text"]}" font-family="{SANS}" font-size="36" font-weight="750">{escape(value)}</text>
  <text x="{x}" y="138" fill="{p["sub"]}" font-family="{MONO}" font-size="11.5">{escape(label)}</text>
  <rect x="{x}" y="152" width="120" height="3" rx="1.5" fill="{p["line"]}"/>
  <rect x="{x}" y="152" width="0" height="3" rx="1.5" fill="{col}">
    <animate attributeName="width" values="0;{max(6, 120 * frac):.0f}" begin="{.2 + i * .2:.1f}s" dur="1s" fill="freeze"/>
  </rect>
</g>''')
    # weekly bars for the last 26 weeks
    weeks = []
    for i in range(0, len(days), 7):
        weeks.append(sum(d["c"] for d in days[i:i + 7]))
    weeks = weeks[-26:]
    peak = max(weeks) if weeks and max(weeks) > 0 else 1
    bx, base, maxh, bw = 660, 196, 130, 16
    bars = []
    for i, v in enumerate(weeks):
        h = max(2, maxh * v / peak)
        x = bx + i * (bw + 4)
        col = p["amber"] if v == peak else p["teal"]
        bars.append(
            f'<rect x="{x}" y="{base}" width="{bw}" height="0" rx="3" fill="{col}" fill-opacity="{.45 + .55 * v / peak:.2f}">'
            f'<animate attributeName="height" values="0;{h:.1f}" begin="{.4 + i * .04:.2f}s" dur=".7s" fill="freeze"/>'
            f'<animate attributeName="y" values="{base};{base - h:.1f}" begin="{.4 + i * .04:.2f}s" dur=".7s" fill="freeze"/>'
            f'</rect>')
    total26 = sum(weeks)
    body = f'''
<rect x="1" y="1" width="{W-2}" height="{H-2}" rx="16" fill="{p["panel"]}" stroke="{p["line"]}"/>
<text x="32" y="48" fill="{p["amber"]}" font-family="{MONO}" font-size="12" letter-spacing="2.6">LIVE TELEMETRY · RECOMPUTED EVERY 6 HOURS</text>
<circle cx="{W-36}" cy="44" r="5" fill="{p["teal"]}"><animate attributeName="opacity" values="1;.2;1" dur="1.4s" repeatCount="indefinite"/></circle>
{"".join(blocks)}
<text x="{bx}" y="48" fill="{p["sub"]}" font-family="{MONO}" font-size="11.5">last 26 weeks · {total26:,} contributions</text>
<line x1="{bx}" y1="{base + 1}" x2="{bx + 26 * (bw + 4) - 4}" y2="{base + 1}" stroke="{p["line"]}"/>
{"".join(bars)}
<text x="32" y="216" fill="{p["mute"]}" font-family="{MONO}" font-size="11">bars rise in order of week · amber = busiest week</text>'''
    return _svg(W, H, "Live GitHub telemetry", body, p)


