def domain_tile(domain, label, repos, total, mode, icon=""):
    p = PAL[mode]
    c = p[DOMAIN_KEY[domain]]
    W, H = 400, 200
    n = len(repos)
    share = n / total if total else 0
    barw = W - 64
    chips, x, y = [], 32, 136
    names = [r["name"] for r in repos if not r.get("fork")][:4] or [r["name"] for r in repos][:4]
    for i, nm in enumerate(names):
        t = _trunc(nm, 20)
        w = 14 + 7.2 * len(t)
        if x + w > W - 24:
            x, y = 32, y + 30
            if y > 166:
                break
        chips.append(
            f'<g opacity="0"><animate attributeName="opacity" values="0;1" begin="{0.4 + i * 0.25:.2f}s" dur=".5s" fill="freeze"/>'
            f'<rect x="{x}" y="{y - 16}" width="{w:.0f}" height="24" rx="12" fill="{c}" fill-opacity=".12" stroke="{c}" stroke-opacity=".45"/>'
            f'<text x="{x + 7}" y="{y}" fill="{p["text"]}" font-family="{MONO}" font-size="11.5">{escape(t)}</text></g>')
        x += w + 8
    more = n - len(chips)
    more_svg = (f'<text x="{W - 32}" y="96" text-anchor="end" fill="{p["mute"]}" font-family="{MONO}" '
                f'font-size="11.5">+{more} more</text>') if more > 0 else ""
